const spriteCache = new Map();

export function disegnaGrigliaPixel(ctx, griglia, x, y, scala = 3, flipX = false, flash = false, rotazione = 0) {
  if (!griglia || !griglia.length) return;
  const key = `${griglia.join('|')}_${flash ? 'F' : 'N'}`;
  let off = spriteCache.get(key);
  if (!off && typeof document !== 'undefined') {
    const h = griglia.length;
    const w = griglia[0].length;
    off = document.createElement('canvas');
    off.width = w;
    off.height = h;
    const octx = off.getContext('2d');
    for (let py = 0; py < h; py++) {
      const riga = griglia[py];
      for (let px = 0; px < w; px++) {
        const ch = riga[px];
        const col = PALETTE[ch];
        if (!col) continue;
        octx.fillStyle = flash ? (ch === 'k' ? '#4a1c14' : '#ffffff') : col;
        octx.fillRect(px, py, 1, 1);
      }
    }
    spriteCache.set(key, off);
  }
  if (!off) return;
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  ctx.translate(Math.round(x), Math.round(y));
  if (rotazione !== 0) ctx.rotate(rotazione);
  if (flipX) ctx.scale(-1, 1);
  const dw = off.width * scala;
  const dh = off.height * scala;
  ctx.drawImage(off, -Math.round(dw / 2), -Math.round(dh / 2), dw, dh);
  ctx.restore();
}

